import { Document, HeadingLevel, Packer, Paragraph, TextRun } from "docx";
import { jsPDF } from "jspdf";
import type { QuizQuestion, StructuredNotes } from "../types";

interface ExportBlock {
  type: "title" | "subtitle" | "h1" | "h2" | "body" | "bullet" | "divider";
  text?: string;
  boldPrefix?: string;
}

function sanitizeFilename(raw: string): string {
  const cleaned = raw
    .replace(/[<>:"/\\|?*]+/g, " ")
    .replace(/\s+/g, "-")
    .replace(/^-+|-+$/g, "")
    .toLowerCase();
  return cleaned.slice(0, 72) || "studymate-notes";
}

function triggerBlobDownload(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function downloadMarkdownFile(filenameBase: string, markdown: string): void {
  const blob = new Blob([markdown], { type: "text/markdown;charset=utf-8" });
  triggerBlobDownload(blob, `${sanitizeFilename(filenameBase)}.md`);
}

function buildNotesBlocks(
  notes: StructuredNotes,
  meta?: { channelTitle?: string; language?: string }
): ExportBlock[] {
  const blocks: ExportBlock[] = [{ type: "title", text: notes.title }];

  const subtitleParts: string[] = [];
  if (meta?.channelTitle) subtitleParts.push(meta.channelTitle);
  if (meta?.language && meta.language !== "Original") {
    subtitleParts.push(`Language: ${meta.language}`);
  }
  subtitleParts.push(`Generated by AI StudyMate`);
  blocks.push({ type: "subtitle", text: subtitleParts.join(" · ") });
  blocks.push({ type: "divider" });

  blocks.push({ type: "h1", text: "Summary" });
  blocks.push({ type: "body", text: notes.summary });

  if (notes.keyConcepts.length > 0) {
    blocks.push({ type: "h1", text: "Key Concepts" });
    for (const concept of notes.keyConcepts) {
      blocks.push({ type: "h2", text: concept.heading });
      blocks.push({ type: "body", text: concept.explanation });
    }
  }

  if (notes.structuredOutline.length > 0) {
    blocks.push({ type: "h1", text: "Structured Study Outline" });
    notes.structuredOutline.forEach((section, idx) => {
      blocks.push({
        type: "h2",
        text: `${String(idx + 1).padStart(2, "0")}. ${section.sectionTitle}`,
      });
      for (const point of section.points) {
        blocks.push({ type: "bullet", text: point });
      }
    });
  }

  if (notes.keyTerms.length > 0) {
    blocks.push({ type: "h1", text: "Key Terms & Definitions" });
    for (const item of notes.keyTerms) {
      blocks.push({
        type: "bullet",
        boldPrefix: `${item.term}: `,
        text: item.definition,
      });
    }
  }

  if (notes.takeaways.length > 0) {
    blocks.push({ type: "h1", text: "Exam & Revision Takeaways" });
    for (const takeaway of notes.takeaways) {
      blocks.push({ type: "bullet", text: takeaway });
    }
  }

  return blocks;
}

function buildQuizBlocks(
  quiz: QuizQuestion[],
  videoTitle: string,
  channelTitle?: string
): ExportBlock[] {
  const blocks: ExportBlock[] = [
    { type: "title", text: `${videoTitle} — Practice Quiz & Answers` },
    {
      type: "subtitle",
      text: [channelTitle, `${quiz.length} Questions`, "AI StudyMate"]
        .filter(Boolean)
        .join(" · "),
    },
    { type: "divider" },
  ];

  quiz.forEach((q, idx) => {
    blocks.push({
      type: "h2",
      text: `${String(idx + 1).padStart(2, "0")}. ${q.question}`,
    });
    q.options.forEach((opt, optIdx) => {
      const letter = String.fromCharCode(65 + optIdx);
      const isCorrect = optIdx === q.correctIndex;
      blocks.push({
        type: "bullet",
        boldPrefix: `${letter}. `,
        text: isCorrect ? `${opt}  [Correct Answer]` : opt,
      });
    });
    if (q.explanation) {
      blocks.push({
        type: "body",
        boldPrefix: "Explanation: ",
        text: q.explanation,
      });
    }
  });

  return blocks;
}

function buildTutorBlocks(
  items: Array<{ q: string; a: string }>,
  videoTitle: string,
  channelTitle?: string
): ExportBlock[] {
  const blocks: ExportBlock[] = [
    { type: "title", text: `${videoTitle} — Lesson Q&A Answers` },
    {
      type: "subtitle",
      text: [channelTitle, `${items.length} Q&A`, "AI StudyMate"]
        .filter(Boolean)
        .join(" · "),
    },
    { type: "divider" },
  ];

  items.forEach((item, idx) => {
    blocks.push({
      type: "h2",
      text: `${String(idx + 1).padStart(2, "0")}. ${item.q}`,
    });
    for (const para of item.a.split(/\n+/)) {
      const clean = para.trim();
      if (clean) {
        blocks.push({ type: "body", text: clean });
      }
    }
  });

  return blocks;
}

async function exportBlocksToDocx(blocks: ExportBlock[], filenameBase: string): Promise<void> {
  const children: Paragraph[] = [];

  for (const block of blocks) {
    if (block.type === "title") {
      children.push(
        new Paragraph({
          text: block.text || "",
          heading: HeadingLevel.TITLE,
          spacing: { after: 120 },
        })
      );
    } else if (block.type === "subtitle") {
      children.push(
        new Paragraph({
          children: [
            new TextRun({
              text: block.text || "",
              color: "64748B",
              size: 20,
            }),
          ],
          spacing: { after: 200 },
        })
      );
    } else if (block.type === "divider") {
      children.push(
        new Paragraph({
          text: "",
          border: {
            bottom: { color: "CBD5E1", size: 6, style: "single" },
          },
          spacing: { after: 220 },
        })
      );
    } else if (block.type === "h1") {
      children.push(
        new Paragraph({
          text: block.text || "",
          heading: HeadingLevel.HEADING_1,
          spacing: { before: 240, after: 100 },
        })
      );
    } else if (block.type === "h2") {
      children.push(
        new Paragraph({
          text: block.text || "",
          heading: HeadingLevel.HEADING_2,
          spacing: { before: 160, after: 80 },
        })
      );
    } else if (block.type === "bullet") {
      const runs: TextRun[] = [];
      if (block.boldPrefix) {
        runs.push(new TextRun({ text: block.boldPrefix, bold: true }));
      }
      runs.push(new TextRun({ text: block.text || "" }));
      children.push(
        new Paragraph({
          children: runs,
          bullet: { level: 0 },
          spacing: { after: 80 },
        })
      );
    } else if (block.type === "body") {
      const runs: TextRun[] = [];
      if (block.boldPrefix) {
        runs.push(new TextRun({ text: block.boldPrefix, bold: true }));
      }
      runs.push(new TextRun({ text: block.text || "" }));
      children.push(
        new Paragraph({
          children: runs,
          spacing: { after: 120 },
        })
      );
    }
  }

  const doc = new Document({
    sections: [
      {
        properties: {},
        children,
      },
    ],
  });

  const blob = await Packer.toBlob(doc);
  triggerBlobDownload(blob, `${sanitizeFilename(filenameBase)}.docx`);
}

function wrapTextLines(
  ctx: CanvasRenderingContext2D,
  text: string,
  maxWidth: number
): string[] {
  const paragraphs = text.split("\n");
  const lines: string[] = [];

  for (const para of paragraphs) {
    const words = para.split(/\s+/).filter(Boolean);
    if (words.length === 0) {
      lines.push("");
      continue;
    }

    let current = "";
    for (const word of words) {
      const candidate = current ? `${current} ${word}` : word;
      if (ctx.measureText(candidate).width <= maxWidth) {
        current = candidate;
      } else {
        if (current) lines.push(current);
        if (ctx.measureText(word).width <= maxWidth) {
          current = word;
        } else {
          let chunk = "";
          for (const ch of Array.from(word)) {
            if (ctx.measureText(chunk + ch).width <= maxWidth) {
              chunk += ch;
            } else {
              if (chunk) lines.push(chunk);
              chunk = ch;
            }
          }
          current = chunk;
        }
      }
    }
    if (current) lines.push(current);
  }

  return lines;
}

function exportBlocksToPdf(blocks: ExportBlock[], filenameBase: string): void {
  const PAGE_W = 794;
  const PAGE_H = 1123;
  const SCALE = 2;
  const MARGIN_X = 56;
  const MARGIN_TOP = 56;
  const MARGIN_BOTTOM = 64;
  const CONTENT_W = PAGE_W - MARGIN_X * 2;
  const FONT_FAMILY =
    '"Plus Jakarta Sans", "Noto Sans Devanagari", "Noto Sans Bengali", "Noto Sans Tamil", "Noto Sans Telugu", "Noto Sans Kannada", "Noto Sans Gujarati", system-ui, -apple-system, sans-serif';

  const pages: HTMLCanvasElement[] = [];

  const createPage = (): { canvas: HTMLCanvasElement; ctx: CanvasRenderingContext2D } => {
    const canvas = document.createElement("canvas");
    canvas.width = PAGE_W * SCALE;
    canvas.height = PAGE_H * SCALE;
    const ctx = canvas.getContext("2d")!;
    ctx.scale(SCALE, SCALE);
    ctx.fillStyle = "#FFFFFF";
    ctx.fillRect(0, 0, PAGE_W, PAGE_H);
    pages.push(canvas);
    return { canvas, ctx };
  };

  let { ctx } = createPage();
  let y = MARGIN_TOP;

  const ensureSpace = (needed: number) => {
    if (y + needed > PAGE_H - MARGIN_BOTTOM) {
      ({ ctx } = createPage());
      y = MARGIN_TOP;
    }
  };

  for (const block of blocks) {
    if (block.type === "divider") {
      ensureSpace(18);
      ctx.strokeStyle = "#E2E8F0";
      ctx.lineWidth = 1;
      ctx.beginPath();
      ctx.moveTo(MARGIN_X, y + 4);
      ctx.lineTo(PAGE_W - MARGIN_X, y + 4);
      ctx.stroke();
      y += 20;
      continue;
    }

    let font = `400 13px ${FONT_FAMILY}`;
    let lineHeight = 20;
    let color = "#334155";
    let spaceBefore = 0;
    let spaceAfter = 8;
    let indent = 0;
    let bullet = false;

    if (block.type === "title") {
      font = `700 22px ${FONT_FAMILY}`;
      lineHeight = 30;
      color = "#0F172A";
      spaceAfter = 6;
    } else if (block.type === "subtitle") {
      font = `500 11.5px ${FONT_FAMILY}`;
      lineHeight = 17;
      color = "#64748B";
      spaceAfter = 10;
    } else if (block.type === "h1") {
      font = `700 15.5px ${FONT_FAMILY}`;
      lineHeight = 22;
      color = "#1E3A8A";
      spaceBefore = 14;
      spaceAfter = 6;
    } else if (block.type === "h2") {
      font = `600 13.5px ${FONT_FAMILY}`;
      lineHeight = 20;
      color = "#0F172A";
      spaceBefore = 10;
      spaceAfter = 4;
    } else if (block.type === "bullet") {
      indent = 16;
      bullet = true;
      spaceAfter = 5;
    }

    y += spaceBefore;
    ctx.font = font;
    ctx.fillStyle = color;

    const fullText = `${block.boldPrefix || ""}${block.text || ""}`;
    const lines = wrapTextLines(ctx, fullText, CONTENT_W - indent);
    ensureSpace(Math.min(lines.length, 2) * lineHeight + 4);

    lines.forEach((line, lineIdx) => {
      ensureSpace(lineHeight);
      ctx.font = font;
      ctx.fillStyle = color;
      if (bullet && lineIdx === 0) {
        ctx.fillText("•", MARGIN_X + 2, y + lineHeight - 5);
      }
      ctx.fillText(line, MARGIN_X + indent, y + lineHeight - 5);
      y += lineHeight;
    });

    y += spaceAfter;
  }

  const pdf = new jsPDF({
    orientation: "portrait",
    unit: "pt",
    format: "a4",
  });

  const pdfW = pdf.internal.pageSize.getWidth();
  const pdfH = pdf.internal.pageSize.getHeight();

  pages.forEach((canvas, idx) => {
    const pageCtx = canvas.getContext("2d")!;
    pageCtx.font = `400 10px ${FONT_FAMILY}`;
    pageCtx.fillStyle = "#94A3B8";
    pageCtx.textAlign = "right";
    pageCtx.fillText(`Page ${idx + 1} of ${pages.length}`, PAGE_W - MARGIN_X, PAGE_H - 28);
    pageCtx.textAlign = "left";
    pageCtx.fillText("AI StudyMate", MARGIN_X, PAGE_H - 28);

    if (idx > 0) pdf.addPage();
    const imgData = canvas.toDataURL("image/jpeg", 0.92);
    pdf.addImage(imgData, "JPEG", 0, 0, pdfW, pdfH);
  });

  pdf.save(`${sanitizeFilename(filenameBase)}.pdf`);
}

export async function downloadNotesAsWord(
  notes: StructuredNotes,
  meta?: { filenameBase?: string; channelTitle?: string; language?: string }
): Promise<void> {
  const blocks = buildNotesBlocks(notes, meta);
  await exportBlocksToDocx(blocks, meta?.filenameBase || notes.title);
}

